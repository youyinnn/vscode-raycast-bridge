#!/usr/bin/env node
/**
 * Extracts the model ids the installed @raycast/api knows about.
 *
 * Two sources are needed and neither is sufficient alone: this enum says which
 * ids the local Raycast can accept -- ids the server has since added are
 * rejected with a Swift decoding error -- while Raycast's catalog endpoint is
 * the only place names, context windows and pricing are published. The
 * extension intersects them. Re-run after updating @raycast/api or Raycast.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TYPES = join(here, "..", "..", "raycast", "node_modules", "@raycast", "api", "types", "index.d.ts");
const OUTPUT = join(here, "..", "src", "models.sdk.ts");

/** Guards against emitting an empty allowlist, which would hide every model. */
const MIN_EXPECTED = 20;

const source = readFileSync(TYPES, "utf8");
const start = source.indexOf("export enum Model {");
if (start === -1) {
  throw new Error(`Could not find "export enum Model" in ${TYPES}`);
}
const body = source.slice(start, source.indexOf("}", start));
const ids = [...new Set([...body.matchAll(/=\s*"([^"]+)"/g)].map(([, id]) => id))].sort();

if (ids.length < MIN_EXPECTED) {
  throw new Error(`Only found ${ids.length} model ids; the enum shape probably changed.`);
}

const version = JSON.parse(
  readFileSync(join(here, "..", "..", "raycast", "node_modules", "@raycast", "api", "package.json"), "utf8"),
).version;

writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-sdk-models.mjs from @raycast/api ${version}.
// Do not edit by hand; run \`npm run gen:models\` after updating @raycast/api.
//
// These are the ids the local Raycast can decode. Raycast's catalog endpoint
// lists more -- the server gains models between Raycast releases -- and passing
// one of those to AI.ask fails with "The data couldn't be read because it isn't
// in the correct format."

/** Probe results are keyed on this, so an SDK bump discards stale verdicts. */
export const SDK_VERSION = ${JSON.stringify(version)};

export const SDK_MODEL_IDS: readonly string[] = [
${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}
];
`,
  "utf8",
);

console.log(`Wrote ${ids.length} model ids from @raycast/api ${version} to ${OUTPUT}`);
